import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const LESSONS_DIR = join(ROOT, 'content', 'lessons');
const OUT_FILE = join(ROOT, 'src', 'catalog.generated.ts');

const VALID_SHAPE_TYPES = new Set([
  'function',
  'segment',
  'line',
  'polygon',
  'circle',
  'rect',
  'text',
  'point',
  'angle',
  'brace',
]);

const VALID_ACTIVITY_TYPES = new Set([
  'single',
  'multiple',
  'scale',
  'short',
  'numeric',
  'canvas',
  'manipulate',
  'make',
]);

function assert(cond, msg) {
  if (!cond) throw new Error(msg);
}

function validateInteractive(inter, ctx) {
  assert(inter && typeof inter === 'object', `${ctx}: interactive 必須為物件`);
  const v = inter.view;
  assert(
    v &&
      typeof v.xMin === 'number' &&
      typeof v.xMax === 'number' &&
      typeof v.yMin === 'number' &&
      typeof v.yMax === 'number' &&
      v.xMax > v.xMin &&
      v.yMax > v.yMin,
    `${ctx}: interactive.view 必須包含合法 xMin < xMax 與 yMin < yMax`
  );
  assert(Array.isArray(inter.shapes), `${ctx}: interactive.shapes 必須為陣列`);
  for (let i = 0; i < inter.shapes.length; i++) {
    const s = inter.shapes[i];
    assert(s && VALID_SHAPE_TYPES.has(s.type), `${ctx}: shape[${i}] 類型 "${s?.type}" 不支援`);
  }
}

function validateActivity(act, ctx) {
  assert(act && typeof act === 'object', `${ctx}: activity 必須為物件`);
  assert(typeof act.id === 'string' && act.id.length > 0, `${ctx}: activity.id 不可為空`);
  assert(VALID_ACTIVITY_TYPES.has(act.type), `${ctx}: 不支援的題型 "${act.type}"`);
  assert(typeof act.prompt === 'string' && act.prompt.length > 0, `${ctx}: activity.prompt 不可為空`);

  if (act.type === 'single' || act.type === 'multiple') {
    assert(Array.isArray(act.options) && act.options.length >= 2, `${ctx}: options 至少需 2 個選項`);
  }
  if (act.type === 'canvas') {
    assert(
      act.rubric && Array.isArray(act.rubric.criteria) && act.rubric.criteria.length > 0,
      `${ctx}: 畫布題 (canvas) 必須附上 rubric.criteria`
    );
  }
  if (act.rubric) {
    assert(Array.isArray(act.rubric.criteria), `${ctx}: rubric.criteria 必須為陣列`);
    for (const c of act.rubric.criteria) {
      assert(typeof c.id === 'string' && c.id, `${ctx}: criterion 缺少 id`);
      assert(typeof c.label === 'string' && c.label, `${ctx}: criterion 缺少 label`);
      assert(typeof c.points === 'number' && c.points > 0, `${ctx}: criterion.points 必須 > 0`);
      assert(Array.isArray(c.levels) && c.levels.length > 0, `${ctx}: criterion "${c.id}" 缺少 levels`);
    }
  }
}

function validateLesson(lesson, filename) {
  const ctx = filename;
  assert(lesson && typeof lesson === 'object', `${ctx}: 檔案內容必須為 JSON 物件`);
  assert(lesson.schemaVersion === 1, `${ctx}: schemaVersion 必須為 1`);
  assert(typeof lesson.id === 'string' && /^[a-z0-9-]+$/i.test(lesson.id), `${ctx}: id 格式不合法`);
  assert(typeof lesson.title === 'string' && lesson.title.length > 0, `${ctx}: 缺少 title`);
  assert(typeof lesson.subject === 'string' && lesson.subject.length > 0, `${ctx}: 缺少 subject`);
  assert(typeof lesson.duration === 'number' && lesson.duration > 0, `${ctx}: duration 必須為正數`);
  assert(Array.isArray(lesson.slides) && lesson.slides.length > 0, `${ctx}: slides 不可為空`);

  const slideIds = new Set();
  const actIds = new Set();

  for (let i = 0; i < lesson.slides.length; i++) {
    const s = lesson.slides[i];
    const sCtx = `${ctx} slide[${i}] (${s?.id || 'unknown'})`;
    assert(typeof s.id === 'string' && s.id.length > 0, `${sCtx}: slide 缺少 id`);
    assert(!slideIds.has(s.id), `${sCtx}: slide.id "${s.id}" 重複`);
    slideIds.add(s.id);
    assert(typeof s.title === 'string' && s.title.length > 0, `${sCtx}: 缺少 title`);
    if (s.interactive) validateInteractive(s.interactive, sCtx);
    if (s.activity) {
      assert(!actIds.has(s.activity.id), `${sCtx}: activity.id "${s.activity.id}" 重複`);
      actIds.add(s.activity.id);
      validateActivity(s.activity, sCtx);
    }
  }
}

const files = readdirSync(LESSONS_DIR)
  .filter((f) => f.endsWith('.json'))
  .sort();

if (files.length === 0) {
  throw new Error('content/lessons/ 中找不到任何 .json 教材檔案');
}

const lessons = [];
const lessonIds = new Set();

for (const file of files) {
  const fullPath = join(LESSONS_DIR, file);
  const parsed = JSON.parse(readFileSync(fullPath, 'utf8'));
  validateLesson(parsed, file);
  assert(!lessonIds.has(parsed.id), `${file}: 課程 id "${parsed.id}" 與其他教材重複`);
  lessonIds.add(parsed.id);
  lessons.push(parsed);
}

mkdirSync(dirname(OUT_FILE), { recursive: true });
const outContent = `// AUTO-GENERATED BY scripts/validate-lessons.mjs — DO NOT EDIT MANUALLY
import type { Lesson } from './types';

export const CATALOG_LESSONS: Lesson[] = ${JSON.stringify(lessons, null, 2)};

export const CATALOG_IDS: string[] = ${JSON.stringify(lessons.map((l) => l.id))};
`;
writeFileSync(OUT_FILE, outContent, 'utf8');
console.log(`✓ 已驗證 ${lessons.length} 份專案教材 (${lessons.map((l) => l.id).join(', ')})，並產生 src/catalog.generated.ts`);
